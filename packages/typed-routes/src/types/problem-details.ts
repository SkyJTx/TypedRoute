import type { RouteValidationTarget } from "./route-definition";
import type { TypeValidator, ValidationIssue } from "./type-validator";

/**
 * RFC 9457 Problem Details for HTTP APIs (`application/problem+json`).
 *
 * @see https://datatracker.ietf.org/doc/html/rfc9457
 */
export interface ProblemDetails {
  /**
   * A URI reference that identifies the problem type. Defaults to `"about:blank"`.
   */
  type: string;
  /**
   * A short, human-readable summary of the problem type.
   */
  title: string;
  /**
   * The HTTP status code generated by the origin server for this occurrence of the problem.
   */
  status: number;
  /**
   * A human-readable explanation specific to this occurrence of the problem.
   */
  detail?: string;
  /**
   * A URI reference that identifies the specific occurrence of the problem.
   */
  instance?: string;
  /**
   * Optional machine-readable error code extension.
   */
  code?: string;
  /**
   * Optional validation target segment when the problem originated from schema validation.
   */
  target?: RouteValidationTarget;
  /**
   * Optional structured validation issues when the problem originated from schema validation.
   */
  issues?: ReadonlyArray<ValidationIssue>;
  /**
   * Optional structured domain details extension.
   */
  details?: unknown;
  /**
   * Additional RFC 9457 problem extension members.
   */
  [key: string]: unknown;
}

/**
 * RFC 9457 Problem Details specialized for request or response validation failures.
 */
export interface ValidationProblemDetails extends ProblemDetails {
  target: RouteValidationTarget;
  issues: ReadonlyArray<ValidationIssue>;
}

/**
 * Options for constructing an RFC 9457 Problem Details response via `problem()`.
 */
export interface ProblemOptions {
  type?: string;
  title?: string;
  instance?: string;
  code?: string;
  target?: RouteValidationTarget;
  issues?: ReadonlyArray<ValidationIssue>;
  details?: unknown;
  headers?: HeadersInit;
  schema?: TypeValidator<unknown, unknown>;
  [key: string]: unknown;
}

const HTTP_STATUS_TITLES: Readonly<Record<number, string>> = Object.freeze({
  400: "Bad Request",
  401: "Unauthorized",
  402: "Payment Required",
  403: "Forbidden",
  404: "Not Found",
  405: "Method Not Allowed",
  406: "Not Acceptable",
  408: "Request Timeout",
  409: "Conflict",
  410: "Gone",
  413: "Content Too Large",
  415: "Unsupported Media Type",
  422: "Unprocessable Content",
  429: "Too Many Requests",
  500: "Internal Server Error",
  501: "Not Implemented",
  502: "Bad Gateway",
  503: "Service Unavailable",
  504: "Gateway Timeout",
});

/**
 * Resolves the standard HTTP reason phrase for a numeric status code.
 */
export function getHttpStatusTitle(status: number): string {
  return HTTP_STATUS_TITLES[status] ?? (status >= 500 ? "Internal Server Error" : "Bad Request");
}
